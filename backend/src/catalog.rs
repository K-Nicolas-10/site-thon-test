use serde::Serialize;

#[derive(Clone, Serialize)]
pub struct Product {
    pub id: String,
    pub slug: String,
    pub name: String,
    pub category: Category,
    pub price_cents: u64,
    pub compare_at_cents: Option<u64>,
    pub short: String,
    pub description: String,
    pub materials: Vec<String>,
    pub sizes: Vec<String>,
    pub colors: Vec<Color>,
    pub rating: f32,
    pub reviews: u32,
    pub badge: Option<String>,
    pub in_stock: bool,
    /// CSS gradient used as the product image placeholder.
    pub swatch: [String; 2],
}

#[derive(Clone, Copy, Debug, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Category {
    Footwear,
    Headwear,
    Accessories,
}

#[derive(Clone, Serialize)]
pub struct Color {
    pub name: String,
    pub hex: String,
}

fn color(name: &str, hex: &str) -> Color {
    Color {
        name: name.into(),
        hex: hex.into(),
    }
}

fn sizes(list: &[&str]) -> Vec<String> {
    list.iter().map(|s| s.to_string()).collect()
}

